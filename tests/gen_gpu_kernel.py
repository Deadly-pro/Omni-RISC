#!/usr/bin/env python3
"""Generate firmware/apps/gpu_kernel_words.h from a .S kernel.

    python3 tests/gen_gpu_kernel.py [firmware/gpu_kernels/vector_add.S] [--out FILE]

F8's point is that a kernel can be pushed into the GPU at run time, so the gate
app needs the assembled words as C data rather than as a hex file the RTL flashes
at synthesis. The hex file itself is gitignored; so is the header this emits.
"""
import argparse
import pathlib
import subprocess
import sys


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("kernel", nargs="?", default="firmware/gpu_kernels/vector_add.S")
    ap.add_argument("--out", default="firmware/apps/gpu_kernel_words.h")
    args = ap.parse_args()

    root = pathlib.Path(__file__).resolve().parent.parent
    src = root / args.kernel
    if not src.exists():
        print("gen_gpu_kernel: no such kernel: %s" % src, file=sys.stderr)
        return 1

    hexf = src.with_suffix(".hex")
    r = subprocess.run([sys.executable, str(root / "scripts" / "gpu_asm.py"), str(src)],
                       capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stdout + r.stderr, file=sys.stderr)
        return r.returncode

    words = [ln.strip() for ln in hexf.read_text().splitlines() if ln.strip()]
    if not words:
        print("gen_gpu_kernel: %s is empty" % hexf, file=sys.stderr)
        return 1

    out = root / args.out
    with out.open("w") as f:
        f.write("/* generated by tests/gen_gpu_kernel.py - do not edit */\n")
        f.write("#ifndef GPU_KERNEL_WORDS_H\n#define GPU_KERNEL_WORDS_H\n\n")
        f.write("#define GPU_KERNEL_LEN %d\n\n" % len(words))
        f.write("static const unsigned short gpu_kernel_words[GPU_KERNEL_LEN] = {\n")
        for i in range(0, len(words), 8):
            f.write("    " + " ".join("0x%s," % w for w in words[i:i + 8]) + "\n")
        f.write("};\n\n#endif /* GPU_KERNEL_WORDS_H */\n")

    print("gen_gpu_kernel: %s -> %s (%d words)" % (args.kernel, args.out, len(words)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
